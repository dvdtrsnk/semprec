import type { Pool } from "pg";
import { runAsSystem } from "@semprec/shared";
import { MIN_PASSWORD_LENGTH, type PublicUser } from "../auth/authActions.js";
import { hashPassword } from "../auth/passwordHash.js";
import { hashToken } from "../auth/token.js";
import { createUser } from "../auth/usersStore.js";
import { requireAffectedRows, withTransaction } from "../db/pool.js";
import { NotFoundError, ValidationError } from "../errors.js";
import { logger } from "./logger.js";
import { provisionTenant } from "./provisionTenant.js";
import { createTenant } from "./tenantsStore.js";

export interface AcceptInvitationInput {
  token: string;
  password: string;
}

/** A pending invitation: not accepted, not revoked and not yet expired. */
const USABLE_INVITE_SQL = `SELECT id, email FROM invites
  WHERE token_hash = $1 AND accepted_at IS NULL AND revoked_at IS NULL AND expires_at > now()`;

/** True when a Postgres error is the named unique-index violation. */
function isUniqueViolation(err: unknown, constraint: string): boolean {
  const pgErr = err as { code?: string; constraint?: string };
  return pgErr?.code === "23505" && pgErr?.constraint === constraint;
}

/**
 * Turns a pending invitation (issue #1040) into an account of its own (issue #1087): a new tenant,
 * a `member` user with the invitation's email bound to it, and the invitation consumed. The tenant id
 * is generated by the database, never taken from the caller.
 *
 * Every unusable token (unknown, expired, revoked, already accepted) and an invitation whose email
 * already belongs to an account reject with the same `NotFoundError("Not found")`, so the answer
 * never tells which applied. A password shorter than `MIN_PASSWORD_LENGTH` rejects with
 * `ValidationError` before the token is looked up, so that answer is the same for any token.
 *
 * The unlocked lookup short-circuits an unusable token before Argon2id runs; the password is hashed
 * outside any transaction. The transaction then re-selects the invitation `FOR UPDATE`, so of two
 * concurrent acceptances of one token the second waits for the first to commit, re-reads the row as
 * accepted and rejects; the tenant, the user and `accepted_at` commit or roll back together.
 *
 * After the commit `provision` (`provisionTenant` in production) seeds the tenant's system databases
 * and makes it `active`. When it throws, `invitation_provisioning_failed` is logged with the tenant id
 * and the error is rethrown: the tenant stays `provisioning`, so the account cannot authenticate,
 * and the next deploy's seed step, which provisions every `provisioning` tenant (#1005), finishes it.
 * The new tenant gets no `tenant_ai_budgets` row, so the AI gateway refuses it until an admin sets caps.
 */
export async function acceptInvitation(
  pool: Pool,
  input: AcceptInvitationInput,
  provision: typeof provisionTenant = provisionTenant,
): Promise<PublicUser> {
  return runAsSystem("invitation-acceptance", async () => {
    if (input.password.length < MIN_PASSWORD_LENGTH) {
      throw new ValidationError(`'password' must be at least ${MIN_PASSWORD_LENGTH} characters`);
    }

    const tokenHash = hashToken(input.token);
    const { rows: found } = await pool.query<{ id: string }>(USABLE_INVITE_SQL, [tokenHash]);
    if (found.length === 0) throw new NotFoundError("Not found");

    const passwordHash = await hashPassword(input.password);

    const { tenantId, user } = await withTransaction(pool, async (client) => {
      const { rows: locked } = await client.query<{ id: string; email: string }>(`${USABLE_INVITE_SQL} FOR UPDATE`, [
        tokenHash,
      ]);
      const invite = locked[0];
      if (!invite) throw new NotFoundError("Not found");

      const newTenantId = await createTenant(client, "provisioning");
      const created = await createUser(client, {
        email: invite.email,
        passwordHash,
        tenantId: newTenantId,
        role: "member",
      }).catch((err: unknown) => {
        // The address got an account after the invitation was issued: the same answer as an unusable token.
        if (isUniqueViolation(err, "users_email_key")) throw new NotFoundError("Not found");
        throw err;
      });

      const consumed = await client.query(
        "UPDATE invites SET accepted_at = now() WHERE id = $1 AND accepted_at IS NULL",
        [invite.id],
      );
      requireAffectedRows(consumed, "consuming the accepted invitation");
      return { tenantId: newTenantId, user: created };
    });

    try {
      await provision(pool, tenantId);
    } catch (err) {
      // Ids only: the email and the token stay out of logs that are not tenant-scoped.
      logger.error({ tenantId }, "invitation_provisioning_failed");
      throw err;
    }

    const { passwordHash: _passwordHash, ...publicUser } = user;
    return publicUser;
  });
}
