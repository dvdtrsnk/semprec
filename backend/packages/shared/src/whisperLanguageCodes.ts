/** Normalizes recognized names and ISO 639-1 codes; unrepresentable or unknown languages return null. */
export function normalizeWhisperLanguage(raw: string | null | undefined): string | null {
  return raw == null ? null : (languages.get(raw.trim().toLowerCase()) ?? null);
}
